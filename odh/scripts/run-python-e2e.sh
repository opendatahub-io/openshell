# Run the supported upstream Python gateway E2E suite and post-process its
# JUnit report. Invoked by e2e-odh-entrypoint.sh through run_child, which
# exec's this script into its own session — a shell function cannot be
# exec'd, so the runner lives here as an executable like the nextest and
# merge helpers.
#
# With --oidc, run the upstream e2e/python/oidc suite plus the fork-only
# odh/tests/oidc coverage against the OpenShift gateway with mandatory OIDC
# authentication (OPENSHELL_E2E_OIDC=1). The OpenShift gateway endpoint and
# the Keycloak issuer must be supplied explicitly through
# OPENSHELL_E2E_OIDC_GATEWAY_ENDPOINT and OPENSHELL_E2E_OIDC_ISSUER; this
# runner never derives or falls back to a local Docker endpoint.
#
# Environment contract with the entrypoint:
#   OPENSHELL_E2E_DEPLOY_GATEWAY  0 in no-deploy mode (drives the endpoint
#                                 override rejection below)
#   OPENSHELL_E2E_PYTEST_PYTHON_FILES  the python_files pattern shared with
#                                 the entrypoint's strict gate check
#   E2E_PARALLEL                  xdist worker count (non-OIDC mode only)
#   OPENSHELL_E2E_PYTHON          optional interpreter override
#   UV_PROJECT_ENVIRONMENT        optional uv project environment
#   OPENSHELL_E2E_OIDC_GATEWAY_ENDPOINT  OpenShift Route endpoint (OIDC mode)
#   OPENSHELL_E2E_OIDC_ISSUER     Keycloak issuer URL (OIDC mode)
#   OPENSHELL_E2E_OIDC_CA_CERT_FILE  optional Keycloak CA bundle for the
#                                 suite's token requests (OIDC mode)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"
source "${SCRIPT_DIR}/python-e2e-common.sh"
PYTHON_BIN="${PYTHON_BIN:-python3}"
mode="${1:-}"
oidc_mode=0
if [[ "${mode}" == "--oidc" ]]; then
	oidc_mode=1
	shift
	mode="${1:-}"
fi

python_test_bin=""

validate_oidc_url() {
	local value="$1" label="$2" expected_path="${3:-}"
	"${python_test_bin}" - "${value}" "${label}" "${expected_path}" <<'PY'
import sys
from urllib.parse import urlparse

value, label, expected_path = sys.argv[1:]
parsed = urlparse(value)
try:
    valid_port = parsed.port is None or 1 <= parsed.port <= 65535
except ValueError:
    valid_port = False
if parsed.scheme != "https" or not parsed.hostname or not valid_port:
    raise SystemExit(f"{label} must be an HTTPS URL with a valid hostname and port: {value}")
if expected_path and parsed.path.rstrip("/") != expected_path:
    raise SystemExit(f"{label} must end with {expected_path}: {value}")
if parsed.query or parsed.fragment:
    raise SystemExit(f"{label} must not contain a query or fragment: {value}")
PY
}

# A leftover endpoint override would split a no-deploy run: the SDK
# session fixtures resolve the gateway from metadata.json while
# test_security_tls.py honors the override, so one pytest run can talk
# to two different gateways. The deploy branch unsets it; reject it
# here because no-deploy has no gateway to re-point.
if [[ "${mode}" != "--collect-only" && "${OPENSHELL_E2E_DEPLOY_GATEWAY:-1}" == 0 && -n "${OPENSHELL_GATEWAY_ENDPOINT:-}" ]]; then
	echo "ERROR: OPENSHELL_GATEWAY_ENDPOINT is set, but no-deploy mode has no gateway to re-point: unset it before running the Python suite" >&2
	exit 2
fi

python_test_bin="$(resolve_python_test_bin "${ROOT}")" || exit 2

if [[ "${oidc_mode}" == 1 && "${mode}" != "--collect-only" ]]; then
	# The OIDC suite must talk to the OpenShift Route with tokens from the
	# per-run Keycloak. Both values are generated by the ODH OIDC fixture;
	# absent values mean the fixture did not run, so fail instead of
	# deriving any local Docker or metadata-based endpoint. Collection is
	# local and needs neither value.
	if [[ -z "${OPENSHELL_E2E_OIDC_GATEWAY_ENDPOINT:-}" ]]; then
		echo "ERROR: OPENSHELL_E2E_OIDC_GATEWAY_ENDPOINT is required for the OIDC suite (the OpenShift Route endpoint); refusing to derive a local endpoint" >&2
		exit 2
	fi
	if [[ -z "${OPENSHELL_E2E_OIDC_ISSUER:-}" ]]; then
		echo "ERROR: OPENSHELL_E2E_OIDC_ISSUER is required for the OIDC suite (the Keycloak issuer); refusing to derive a local identity provider" >&2
		exit 2
	fi
	if ! validate_oidc_url "${OPENSHELL_E2E_OIDC_GATEWAY_ENDPOINT}" gateway_endpoint; then
		echo "ERROR: OPENSHELL_E2E_OIDC_GATEWAY_ENDPOINT must be an HTTPS OpenShift Route endpoint" >&2
		exit 2
	fi
	if ! validate_oidc_url "${OPENSHELL_E2E_OIDC_ISSUER}" issuer "/realms/openshell"; then
		echo "ERROR: OPENSHELL_E2E_OIDC_ISSUER must be the HTTPS /realms/openshell issuer" >&2
		exit 2
	fi
	issuer_base="${OPENSHELL_E2E_OIDC_ISSUER%/realms/openshell}"
	if [[ -n "${OPENSHELL_KEYCLOAK_URL:-}" && "${OPENSHELL_KEYCLOAK_URL}" != "${issuer_base}" ]]; then
		echo "ERROR: OPENSHELL_KEYCLOAK_URL conflicts with the configured OIDC issuer" >&2
		exit 2
	fi
	export OPENSHELL_KEYCLOAK_URL="${issuer_base}"
fi

prepare_python_e2e_environment "${ROOT}" "${SCRIPT_DIR}"
if [[ "${oidc_mode}" == 1 ]]; then
	# The suite's token requests must trust the per-run Keycloak CA.
	if [[ -n "${OPENSHELL_E2E_OIDC_CA_CERT_FILE:-}" ]]; then
		[[ -r "${OPENSHELL_E2E_OIDC_CA_CERT_FILE}" ]] || {
			echo "ERROR: OPENSHELL_E2E_OIDC_CA_CERT_FILE is not readable: ${OPENSHELL_E2E_OIDC_CA_CERT_FILE}" >&2
			exit 2
		}
		export SSL_CERT_FILE="${OPENSHELL_E2E_OIDC_CA_CERT_FILE}"
		export REQUESTS_CA_BUNDLE="${OPENSHELL_E2E_OIDC_CA_CERT_FILE}"
	fi
fi
pytest_args=(
	-p no:cacheprovider
	-p pytest_odh_gates
	-o "python_files=${OPENSHELL_E2E_PYTEST_PYTHON_FILES:-test_*.py *_test.py}"
	-m "not gpu"
)
if [[ "${oidc_mode}" == 1 ]]; then
	export PYTHONPATH="${ROOT}/odh/tests/oidc:${PYTHONPATH}"
	# The upstream OIDC suite plus the fork-only multi-user coverage under
	# odh/tests/oidc (same fixture, same gateway, one pytest invocation).
	pytest_args+=(-p oidc_credentials_plugin e2e/python/oidc odh/tests/oidc)
else
	pytest_args+=(e2e/python)
fi
if [[ "${mode}" == "--collect-only" ]]; then
	if [[ $# -ne 1 ]]; then
		echo "Usage: $0 [--oidc] <report.xml>|--collect-only" >&2
		exit 2
	fi
	if [[ "${oidc_mode}" == 1 ]]; then
		echo "==> Collecting ODH OIDC Python gateway E2E suite"
		collect_status=0
		collect_output="$(cd "${ROOT}" && OPENSHELL_E2E_OIDC=1 \
			"${python_test_bin}" -m pytest "${pytest_args[@]}" -p no:xdist --collect-only -q 2>&1)" || collect_status=$?
	else
		echo "==> Collecting ODH Python gateway E2E gates"
		collect_status=0
		collect_output="$(cd "${ROOT}" && OPENSHELL_E2E_OIDC=0 \
			"${python_test_bin}" -m pytest "${pytest_args[@]}" -p no:xdist --collect-only -q 2>&1)" || collect_status=$?
	fi
	if [[ "${collect_status}" != 0 ]]; then
		printf '%s\n' "${collect_output}" >&2
	fi
	exit "${collect_status}"
fi
if [[ -z "${mode}" || $# -ne 1 ]]; then
	echo "Usage: $0 [--oidc] <report.xml>|--collect-only" >&2
	exit 2
fi
report="${mode}"
[[ "${report}" == /* ]] || report="${ROOT}/${report}"
junit_report="${report}"
status=0
oidc_scratch_dir=""
# shellcheck disable=SC2329
cleanup_oidc_scratch() {
	if [[ -n "${oidc_scratch_dir}" && -d "${oidc_scratch_dir}" ]]; then
		rm -rf -- "${oidc_scratch_dir}"
	fi
}
if [[ "${oidc_mode}" == 1 ]]; then
	echo "==> Running ODH OIDC Python gateway E2E against ${OPENSHELL_E2E_OIDC_GATEWAY_ENDPOINT}"
	# Capture the full pytest stdout/stderr privately first. Redact it before
	# writing the retained log or publishing any of it to the caller; otherwise
	# tee would expose a bearer token in CI output before the later redaction.
	# OIDC suite mutates shared workspace membership, so it runs
	# single-process; the normal lane keeps its xdist worker count.
	results_dir="${OPENSHELL_E2E_RESULTS_DIR:-$(dirname "${report}")}"
	pytest_log="${results_dir}/oidc-${OPENSHELL_E2E_RUN_ID:-manual}-pytest.log"
	mkdir -p "${results_dir}"
	rm -f -- "${report}" "${pytest_log}"
	oidc_scratch_dir="$(mktemp -d "${TMPDIR:-/tmp}/openshell-oidc-pytest.XXXXXX")"
	chmod 700 "${oidc_scratch_dir}"
	trap cleanup_oidc_scratch EXIT
	trap 'exit 130' INT
	trap 'exit 143' TERM
	pytest_raw_log="${oidc_scratch_dir}/pytest.log"
	junit_report="${oidc_scratch_dir}/report.xml"
	pytest_status=0
	(cd "${ROOT}" && OPENSHELL_E2E_OIDC=1 OPENSHELL_E2E_OIDC_SCOPES=1 \
		"${python_test_bin}" -m pytest "${pytest_args[@]}" -p no:xdist \
		--junitxml "${junit_report}") >"${pytest_raw_log}" 2>&1 || pytest_status=$?
	status="${pytest_status}"
else
	echo "==> Running ODH Python gateway E2E"
	(cd "${ROOT}" && OPENSHELL_E2E_OIDC=0 \
		"${python_test_bin}" -m pytest "${pytest_args[@]}" -n "${E2E_PARALLEL:-5}" \
		--junitxml "${report}") || status=$?
fi

# Strip skipped testcases from the JUnit report and require at least one
# executed case in the same pass: DevTestOps CI parses the XML and would
# create a Jira for every skipped case, and this lane intentionally skips
# a sizeable share of its collected cases through gates, so an upstream
# or environment change that skips the remaining supported tests must
# fail the phase instead of reporting a vacuous pass. The helper also
# recomputes the suite attributes so the merged report stays
# self-consistent.
if [[ -f "${junit_report}" ]]; then
	strip_status=0
	"${python_test_bin}" "${SCRIPT_DIR}/strip-skipped-testcases.py" "${junit_report}" || strip_status=$?
	case "${strip_status}" in
		0) ;;
		1)
			if [[ "${status}" == 0 ]]; then
				echo "ERROR: Python gateway E2E executed no test cases (every collected case was skipped)" >&2
				status=1
			fi
			;;
		*)
		echo "ERROR: failed to post-process JUnit report ${junit_report} (${strip_status})" >&2
		[[ "${status}" != 0 ]] || status="${strip_status}"
			;;
	esac
fi
# The OIDC report and pytest log can carry token-bearing failure output. Keep
# both raw artifacts private and publish only a successfully redacted result.
publish_redacted_artifact() {
	local artifact="$1" destination="$2" description="$3" redact_mode="${4:-}" redact_status
	local redacted_artifact
	redacted_artifact="${oidc_scratch_dir}/$(basename "${destination}").redacted"
	local redact_args=("${artifact}" "${redacted_artifact}")
	if [[ -n "${redact_mode}" ]]; then
		redact_args+=("${redact_mode}")
	fi
	if "${python_test_bin}" "${SCRIPT_DIR}/redact-oidc-artifact.py" "${redact_args[@]}"; then
		mv -f "${redacted_artifact}" "${destination}"
		rm -f -- "${artifact}"
	else
		redact_status=$?
		rm -f -- "${artifact}" "${redacted_artifact}" "${destination}"
		echo "ERROR: failed to redact OIDC ${description}; removed both files" >&2
		[[ "${status}" != 0 ]] || status="${redact_status}"
	fi
}

if [[ "${oidc_mode}" == 1 ]]; then
	if [[ -f "${junit_report}" ]]; then
		publish_redacted_artifact "${junit_report}" "${report}" "JUnit report" --xml
	fi
	if [[ -f "${pytest_raw_log}" ]]; then
		publish_redacted_artifact "${pytest_raw_log}" "${pytest_log}" "pytest log"
		[[ -f "${pytest_log}" ]] && cat "${pytest_log}"
	fi
fi
if [[ "${status}" == 5 ]]; then
	echo "ERROR: Python gateway E2E selected no tests" >&2
fi

if [[ ! -f "${report}" ]]; then
	echo "ERROR: Python gateway E2E did not write a JUnit report" >&2
	[[ "${status}" != 0 ]] || status=1
fi
exit "${status}"
